#!/usr/bin/env node
// Builds client/js/worldmap-data.js: every country as a compact SVG path on an Equal Earth
// projection, with its ISO 3166-1 alpha-2 code and English name, plus a pin for each
// destination. Run it again only if you change the projection or the destinations:
//
//   npm install && node tools/build-world-map.js
//
// Country shapes: Natural Earth 1:110m (public domain), packaged as TopoJSON by world-atlas.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';
import countries from 'i18n-iso-countries';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const geo = feature(topo, topo.objects.countries);

// Equal Earth projection (Šavrič, Patterson & Jenny, 2018).
const A1 = 1.340264;
const A2 = -0.081106;
const A3 = 0.000893;
const A4 = 0.003796;
const M = Math.sqrt(3) / 2;
function project(lon, lat) {
  const l = (lon * Math.PI) / 180;
  const t = Math.asin(M * Math.sin((lat * Math.PI) / 180));
  const t2 = t * t;
  const t6 = t2 * t2 * t2;
  const x = (l * Math.cos(t)) / (M * (A1 + 3 * A2 * t2 + t6 * (7 * A3 + 9 * A4 * t2)));
  const y = t * (A1 + A2 * t2 + t6 * (A3 + A4 * t2));
  return [x, -y];
}

const WIDTH = 1000;
const TOP = 84;
const BOTTOM = -57;
const [x0] = project(-180, 0);
const [x1] = project(180, 0);
const [, y0] = project(0, TOP);
const [, y1] = project(0, BOTTOM);
const scale = WIDTH / (x1 - x0);
const HEIGHT = Math.round((y1 - y0) * scale);
const toMap = (lon, lat) => {
  const [x, y] = project(lon, Math.max(BOTTOM, Math.min(TOP, lat)));
  return [(x - x0) * scale, (y - y0) * scale];
};

const r1 = (v) => Math.round(v * 10) / 10;
const fmt = (v) => {
  const s = r1(v).toFixed(1).replace(/\.0$/, '');
  return s.startsWith('0.') ? s.slice(1) : s.startsWith('-0.') ? `-${s.slice(2)}` : s;
};

function ringPath(ring) {
  const pts = [];
  for (const [lon, lat] of ring) {
    const p = toMap(lon, lat).map(r1);
    const last = pts[pts.length - 1];
    if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= 0.7) pts.push(p);
  }
  if (pts.length < 3) return null;
  let area = 0;
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i];
    const b = pts[(i + 1) % pts.length];
    area += a[0] * b[1] - b[0] * a[1];
  }
  if (Math.abs(area / 2) < 0.6) return null;
  let d = `M${fmt(pts[0][0])} ${fmt(pts[0][1])}l`;
  for (let i = 1; i < pts.length; i++) {
    const dx = pts[i][0] - pts[i - 1][0];
    const dy = pts[i][1] - pts[i - 1][1];
    d += `${fmt(dx)}${dy < 0 ? '' : ' '}${fmt(dy)} `;
  }
  return `${d.trim()}z`;
}

const out = [];
for (const f of geo.features) {
  if (f.id === '010') continue; // Antarctica
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const d = polys
    .flatMap((poly) => poly.map(ringPath))
    .filter(Boolean)
    .join('');
  if (!d) continue;
  const a2 = f.id ? countries.numericToAlpha2(f.id) ?? '' : '';
  out.push([a2, f.properties.name, d]);
}
out.sort((a, b) => a[1].localeCompare(b[1]));

// Where each destination's pin goes: Giza, Rome, Kyoto and Barcelona.
const PINS = {
  egypt: toMap(31.13, 29.98).map(r1),
  italy: toMap(12.49, 41.89).map(r1),
  japan: toMap(135.77, 35.01).map(r1),
  spain: toMap(2.17, 41.39).map(r1),
};

const body = `// Generated by tools/build-world-map.js. Do not edit by hand.
// Country shapes: Natural Earth 1:110m (public domain), via world-atlas (ISC licence),
// on an Equal Earth projection. Each country is [ISO alpha-2 code, English name, SVG path].

export const MAP_W = ${WIDTH};
export const MAP_H = ${HEIGHT};
export const PINS = ${JSON.stringify(PINS)};
export const COUNTRIES = [
${out.map((c) => `  ${JSON.stringify(c)},`).join('\n')}
];
`;
const file = new URL('../client/js/worldmap-data.js', import.meta.url);
writeFileSync(file, body);
console.log(`wrote ${out.length} countries, ${(body.length / 1024).toFixed(1)} KiB, ${WIDTH}x${HEIGHT}`);
